"""
Data models (Pydantic) used by all three agents.

There are two kinds of model here:

1. STATE models: the shared "notebook" that travels through every node of a
   LangGraph graph. Each node reads the fields it needs and writes back the
   fields it produced. One per agent:
     - AgentSchema      -> SQL analyst  (agents/sql_analyst.py)
     - ETLAgentSchema   -> ETL analyst  (agents/etl_analyst.py)
     - DataAgentSchema  -> Data agent / router (agents/data_agent.py)

2. STRUCTURED OUTPUT models: the exact shape an LLM must answer in. Instead of
   letting the LLM reply with free text, llm.with_structured_output(Model)
   forces it to fill in these fields, so the code can read the answer reliably.
     - JudgeSchema  -> the SQL safety judge (is_safe + comments)
     - RouteSchema  -> the router (answer = "sql" | "etl" + comments)

Learning notes:
- Pydantic's BaseModel validates data when an object is created. If a field
  has the wrong type (e.g. is_safe = "maybe"), it raises a ValidationError
  instead of silently accepting bad data.
- Field(...)  -> the "..." (Ellipsis) means "this field is required".
- Field(None) -> the field is optional and starts as None.
- description="..." is metadata. For JudgeSchema it matters a lot: the
  descriptions are sent to the LLM as part of the output format, so they work
  like mini instructions.
"""

from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add


#------ Classes for SQL analyst agent -------------------------------------------------------------

class AgentSchema(BaseModel):
    """State shared by all nodes of the SQL analyst graph."""

    # --- Conversation history -------------------------------------------------
    # Annotated[list, add] attaches a "reducer" to the field.
    # A reducer tells LangGraph HOW to merge a node's update into the state:
    #   - without a reducer, a new value REPLACES the old one
    #   - with `add` (operator.add, i.e. list + list), the new list is APPENDED
    #     to the old one
    # That's why nodes return only the NEW messages, e.g. {"messages": [AIMessage(...)]}.
    # Returning the full list would append everything again (duplicated history).
    messages : Annotated[list, add] = Field(..., description="List of messages to be processed by the agent")

    # --- Input ----------------------------------------------------------------
    # The raw question, kept separate from `messages` so it's easy to track and
    # debug, and so we control when/how it is added to the conversation.
    user_input: str = Field(..., description="Original uer input asked by the user.")

    # --- Values filled in as the graph runs -------------------------------------
    # Node 1 (curate_question): a clearer version of user_input.
    curated_question : str = Field(..., description="Curated user question")

    # Node 2 (prompt_query_context): the full prompt for the SQL generator
    # (instructions + question + database schema + sample rows).
    prompt_query_context : str = Field(..., description="A detailed prompt with SQL DB context that will help agent to generate SQL query")

    # Node 4 (is_safe_sql): the judge's verdict.
    # Literal["Yes", "No"] restricts the value to exactly those two strings.
    # `| None` + default None lets the field start empty, because it only gets
    # a value after the judge runs. (An empty string "" would fail validation.)
    is_safe : Literal["Yes", "No"] | None = Field(None, description="A boolean flag indicating whether the generated SQL query is safe to execute or not")
    comments : str = Field(..., description="Comments or feedback provided by the judge regarding the safety of the SQL query")

    # Node 3 (generate_sql): the SQL written by the LLM.
    generated_sql_query : str = Field(..., description="The SQL query generated by the agent based on the curated question and prompt query context")

    # Node 5 (execute_sql): the rows returned by Postgres, as text
    # (or an "Error executing query: ..." message if the query failed).
    sql_query_execution_result : str = Field(..., description="The result of executing the generated SQL query against the database")

    # Last node (represent_final_answer or canceled_sql): the answer shown to the user.
    final_answer : str = Field(..., description="The final answer generated by the agent based on the SQL query execution result and the curated question")


class JudgeSchema(BaseModel):
    """
    Shape of the safety judge's answer.

    Used with llm.with_structured_output(JudgeSchema): LangChain turns this
    class into a JSON schema, sends it to the model, and parses the reply back
    into a JudgeSchema object. Because is_safe is a Literal, the model can only
    answer "Yes" or "No".
    """
    is_safe : Literal["Yes", "No"] = Field(..., description="A boolean flag indicating whether the generated SQL query is safe to execute or not")
    comments : str = Field(..., description="Comments or feedback provided by the judge regarding the safety of the SQL query")





#------ Classes for ETL analyst agent -------------------------------------------------------------

class ETLAgentSchema(BaseModel):
    """State shared by all nodes of the ETL analyst graph."""

    # --- Conversation history -------------------------------------------------
    # The only field. A tool-calling (ReAct) agent keeps everything in the
    # message list: the user request, the LLM's tool calls (AIMessage), the
    # tool results (ToolMessage) and the final answer. The LLM re-reads this
    # list on every turn to decide what to do next.
    # `add` reducer: nodes return only their NEW messages, which get appended.
    messages : Annotated[list, add] = Field(..., description="List of messages to be processed by the agent")


#------ Classes for orchestration agent -------------------------------------------------------------
# Shape of the router's answer (structured output).
# Used with llm.with_structured_output(RouteSchema) in data_agent.py.
# Literal["sql", "etl"] means the model can only pick one of these two, so the
# conditional edge can trust the value. The field descriptions are sent to the
# LLM, so they act as instructions.
# (Written as comments, not a docstring: a class docstring is ALSO sent to the
# LLM as the schema description, which would change the router's prompt.)
class RouteSchema(BaseModel):
    answer: Literal["sql","etl"] = Field(..., description="Indicates whether the user's question is related to SQL or ETL operations")
    # Not used by the graph, but asking the model to explain its choice helps
    # when debugging a wrong route (and can improve the choice itself).
    comments: str = Field(..., description="Additional comments or feedback regarding the classification of the user's question")

# State shared by all nodes of the Data agent (router) graph.
class DataAgentSchema(BaseModel):
    # Conversation history: the user's request, then the specialist's answer.
    # `add` reducer, same as above.
    messages : Annotated[list,add] = Field(..., description="List of messages to be processed by the Data agent")
    # Written by router_node ("sql" or "etl"), read by the conditional edge.
    # Typed as plain str (not Literal) so the run can start with "".
    route_response : str = Field(..., description="The response from the router indicating whether to route to SQL or ETL operations")