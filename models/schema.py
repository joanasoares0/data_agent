from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add

class AgentSchema(BaseModel):
    # annotated helper function to add metadata to the field, this way we know that we will be adding messages to a list of messages, 
    # with annotated langchain or langgraph will do it automatically
    messages : Annotated[list, add] = Field(..., description="List of messages to be processed by the agent")

    # we could also add user input to messages or we can keep it separate
    # have a fresh user input separated to make things easier to track and debug, and also to make it easier to add the user input to the messages list in a controlled way.
    user_input: str = Field(..., description="Original uer input asked by the user.")

    curated_question : str = Field(..., description="Curated user question")

    prompt_query_context : str = Field(..., description="A detailed prompt with SQL DB context that will help agent to generate SQL query")

    is_safe : Literal["Yes", "No"] = Field(..., description="A boolean flag indicating whether the generated SQL query is safe to execute or not")

    generated_sql_query : str = Field(..., description="The SQL query generated by the agent based on the curated question and prompt query context")

    sql_query_execution_result : str = Field(..., description="The result of executing the generated SQL query against the database")

    final_answer : str = Field(..., description="The final answer generated by the agent based on the SQL query execution result and the curated question")
    